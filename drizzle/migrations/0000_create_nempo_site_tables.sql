  created_at timestamptz not null default now(), email text not null, full_name text not null, hobby text,
  interest text not null, origin_name text, origin_type text, reason text, whatsapp text not null,
  constraint community_applications_lengths check (
    char_length(full_name) between 1 and 120 and char_length(email) between 3 and 255
    and char_length(whatsapp) between 6 and 30 and char_length(interest) between 1 and 120
    and coalesce(char_length(reason), 0) <= 2000 and coalesce(char_length(hobby), 0) <= 500
